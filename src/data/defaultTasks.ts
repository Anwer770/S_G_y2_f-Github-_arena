export const DEFAULT_TASKS: Task[] = Array.from({ length: 103 }, (_, index) => {
  const item = initialRawTasks[index % initialRawTasks.length];
  const taskIdNum = String(index + 1).padStart(4, '0');
  const subNum = String((index % 30) + 1).padStart(4, '0');
  
  // Distribute statuses across the 103 items to ensure realistic metrics
  let status: any = item.status;
  if (index >= 30 && index < 55) status = 'قيد التنفيذ';
  else if (index >= 55 && index < 75) status = 'مخطط';
  else if (index >= 75 && index < 85) status = 'تم الانجاز';
  else if (index >= 85 && index < 93) status = 'متأخر';
  else if (index >= 93 && index < 98) status = 'مؤجل';
  else if (index >= 98) status = 'ملغي';

  // Format date offset to give rich monthly and calendar distribution
  const dayOffset = (index * 2) % 60;
  const startDate = new Date(2024, 9, 1);
  startDate.setDate(startDate.getDate() + dayOffset);
  const startStr = startDate.toISOString().split('T')[0];

  const endDate = new Date(startDate);
  endDate.setDate(endDate.getDate() + ((index % 4) + 1));
  const endStr = endDate.toISOString().split('T')[0];

  return {
    id: `T-${taskIdNum}`,
    sub: `${item.cat}-${subNum}`,
    start: startStr,
    end: endStr,
    title: index < initialRawTasks.length ? item.title : `${item.title} (متابعة مرحلية #${index + 1})`,
    desc: `تفاصيل متابعة العمل والتنسيق المباشر لـ ${item.title} مع الجهات المعنية.`,
    cat: item.cat,
    op: item.op,
    pri: (item.pri as any) || 'B',
    status: status,
    resp: item.resp,
    amount: item.amount ? item.amount + (index * 500) : undefined,
    createdAt: new Date(startDate.getTime() - 86400000).toISOString(),
    updatedAt: new Date().toISOString(),
  };
});
